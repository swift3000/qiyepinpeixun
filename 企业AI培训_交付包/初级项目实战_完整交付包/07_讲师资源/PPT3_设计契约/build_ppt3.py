def card_spec(c):
    (code, name, sub, s1l, s1d, s2l, s2d, s3l, s3d,
     al, ad, bl, bd, cl, cd, dl, dd, el, ed, dur, dm) = c
    new = [f"{code} · {name}", sub, s1l, s1d, s2l, s2d, s3l, s3d,
           al, ad, bl, bd, cl, cd, dl, dd, el, ed, dur, dm]
    assert len(new) == len(CARD_OLD), f"{code}: new={len(new)} 应等于 {len(CARD_OLD)}"
    return dict(zip(CARD_OLD, new))


def build_replace():
    rep = {1: R1, 2: R2, 3: R3, 4: R4, 5: R5, 32: R32, 33: R33}
    for i, c in enumerate(CARDS):
        rep[6 + i] = card_spec(c)
    return rep


FOOTER_OLD = "通用 AI 基础 · 初级"
FOOTER_NEW = "实战项目执行手册"
PAGENO_RE = re.compile(r"^\s*\d{1,2}\s*/\s*38\s*$")  # donor PPT1-v2 现为 38 页


def clone_slide(prs, donor):
    s = prs.slides.add_slide(donor.slide_layout)
    spTree = s.shapes._spTree
    for child in list(spTree):
        if child.tag.endswith("}nvGrpSpPr") or child.tag.endswith("}grpSpPr"):
            continue
        spTree.remove(child)
    dcs = donor._element.find(qn("p:cSld"))
    scs = s._element.find(qn("p:cSld"))
    dbg = dcs.find(qn("p:bg"))
    if dbg is not None:
        scs.insert(0, copy.deepcopy(dbg))
    for child in donor.shapes._spTree:
        if child.tag.endswith("}nvGrpSpPr") or child.tag.endswith("}grpSpPr"):
            continue
        spTree.append(copy.deepcopy(child))
    for rId, rel in list(donor.part.rels.items()):
        if "notesSlide" in rel.reltype:
            continue
        if rel.is_external:
            new_id = s.part.relate_to(rel.target_ref, rel.reltype, is_external=True)
        else:
            new_id = s.part.relate_to(rel.target_part, rel.reltype)
        if new_id != rId:
            for el in s._element.iter():
                for k, v in list(el.attrib.items()):
                    if v == rId:
                        el.set(k, new_id)
    return s


def set_text(shape, text):
    tf = shape.text_frame
    txBody = tf._txBody
    ps = txBody.findall(qn("a:p"))
    pPr = None
    rPr = None
    for p in ps:
        el = p.find(qn("a:pPr"))
        if pPr is None and el is not None:
            pPr = copy.deepcopy(el)
        for r in p.findall(qn("a:r")):
            el = r.find(qn("a:rPr"))
            if el is not None:
                rPr = copy.deepcopy(el)
                break
        if rPr is not None:
            break
    for p in ps:
        txBody.remove(p)
    for line in text.split("\n"):
        p = txBody.makeelement(qn("a:p"), {})
        if pPr is not None:
            p.append(copy.deepcopy(pPr))
        r = p.makeelement(qn("a:r"), {})
        if rPr is not None:
            r.append(copy.deepcopy(rPr))
        t = r.makeelement(qn("a:t"), {})
        t.text = line
        r.append(t)
        p.append(r)
        txBody.append(p)


def walk_shapes(shapes):
    for sh in shapes:
        if sh.shape_type == 6:  # group
            yield from walk_shapes(sh.shapes)
        else:
            yield sh


def replace_on_slide(slide, mapping, page_no):
    found = {old: [] for old in mapping}
    for sh in walk_shapes(slide.shapes):
        if sh.has_text_frame:
            t = sh.text_frame.text.strip()
            if t in found:
                found[t].append(sh)
    for old, new in mapping.items():
        n = len(found[old])
        assert n == 1, f"P{page_no} 匹配失败 {old!r}: 命中 {n} 处"
        set_text(found[old][0], new)


def main():
    prs = Presentation(SRC)
    orig = list(prs.slides)
    assert len(orig) == 38, f"PPT1-v2 应为 38 页，实际 {len(orig)}"
    orig_sldIds = list(prs.slides._sldIdLst)

    rep = build_replace()
    new_slides = []
    for target, d in DONOR.items():
        donor = orig[d - 1]
        s = clone_slide(prs, donor)
        new_slides.append((target, s))

    for target, s in new_slides:
        replace_on_slide(s, rep[target], target)

    # 全局页脚
    for target, s in new_slides:
        for sh in walk_shapes(s.shapes):
            if not sh.has_text_frame:
                continue
            txt = sh.text_frame.text.strip()
            if txt == FOOTER_OLD:
                set_text(sh, FOOTER_NEW)
            elif PAGENO_RE.match(txt):
                set_text(sh, f"{target} / 33")

    sldIdLst = prs.slides._sldIdLst
    for sldId in orig_sldIds:
        rId = sldId.get(qn("r:id"))
        prs.part.drop_rel(rId)
        sldIdLst.remove(sldId)

    prs.save(OUT)
    check = Presentation(OUT)
    print(f"OK 已生成 {OUT}，共 {len(list(check.slides))} 页")


if __name__ == "__main__":
    main()
