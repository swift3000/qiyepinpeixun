FOOTER_OLD = "通用 AI 基础 · 初级"
FOOTER_NEW = "实战项目工作坊 · 初级"
PAGENO_RE = re.compile(r"^\s*\d{1,2}\s*/\s*33\s*$")


def clone_slide(prs, donor):
    s = prs.slides.add_slide(donor.slide_layout)
    spTree = s.shapes._spTree
    for child in list(spTree):
        if child.tag.endswith("}nvGrpSpPr") or child.tag.endswith("}grpSpPr"):
            continue
        spTree.remove(child)
    dcs = donor._element.find(qn("p:cSld"))
    scs = s._element.find(qn("p:cSld"))
    dbg = dcs.find(qn("p:bg"))
    if dbg is not None:
        scs.insert(0, copy.deepcopy(dbg))
    dTree = donor.shapes._spTree
    for child in dTree:
        if child.tag.endswith("}nvGrpSpPr") or child.tag.endswith("}grpSpPr"):
            continue
        spTree.append(copy.deepcopy(child))
    for rId, rel in list(donor.part.rels.items()):
        if "notesSlide" in rel.reltype:
            continue
        if rel.is_external:
            new_id = s.part.relate_to(rel.target_ref, rel.reltype, is_external=True)
        else:
            new_id = s.part.relate_to(rel.target_part, rel.reltype)
        if new_id != rId:
            for el in s._element.iter():
                for k, v in list(el.attrib.items()):
                    if v == rId:
                        el.set(k, new_id)
    return s


def set_text(shape, text):
    tf = shape.text_frame
    txBody = tf._txBody
    ps = txBody.findall(qn("a:p"))
    pPr = None
    rPr = None
    for p in ps:
        el = p.find(qn("a:pPr"))
        if pPr is None and el is not None:
            pPr = copy.deepcopy(el)
        for r in p.findall(qn("a:r")):
            el = r.find(qn("a:rPr"))
            if el is not None:
                rPr = copy.deepcopy(el)
                break
        if rPr is not None:
            break
    for p in ps:
        txBody.remove(p)
    for line in text.split("\n"):
        p = txBody.makeelement(qn("a:p"), {})
        if pPr is not None:
            p.append(copy.deepcopy(pPr))
        r = p.makeelement(qn("a:r"), {})
        if rPr is not None:
            r.append(copy.deepcopy(rPr))
        t = r.makeelement(qn("a:t"), {})
        t.text = line
        r.append(t)
        p.append(r)
        txBody.append(p)


def main():
    prs = Presentation(SRC)
    orig = list(prs.slides)
    assert len(orig) == 33, f"PPT1 应为 33 页，实际 {len(orig)}"
    orig_sldIds = list(prs.slides._sldIdLst)  # 克隆前记录，最后只删这 33 条

    new_slides = []
    for target, d in DONOR.items():
        donor = orig[d - 1]
        s = clone_slide(prs, donor)
        new_slides.append(s)
        assert len(s.shapes) == len(donor.shapes), (
            f"P{target} 克隆 shape 数不符: {len(s.shapes)} != {len(donor.shapes)}"
        )

    for target, s in enumerate(new_slides, 1):
        shapes = list(s.shapes)
        for idx, text in SPEC.get(target, []):
            assert shapes[idx].has_text_frame, f"P{target}[{idx}] 无文本框"
            set_text(shapes[idx], text)
        for idx in DELETE.get(target, []):
            el = shapes[idx]._element
            el.getparent().remove(el)

    # 全局页脚手术
    for target, s in enumerate(new_slides, 1):
        for shp in s.shapes:
            if not shp.has_text_frame:
                continue
            txt = shp.text_frame.text.strip()
            if txt == FOOTER_OLD:
                set_text(shp, FOOTER_NEW)
            elif PAGENO_RE.match(txt):
                set_text(shp, f"{target} / 33")

    # 删原 33 页（只删克隆前记录的那批）
    sldIdLst = prs.slides._sldIdLst
    for sldId in orig_sldIds:
        rId = sldId.get(qn("r:id"))
        prs.part.drop_rel(rId)
        sldIdLst.remove(sldId)

    prs.save(OUT)
    check = Presentation(OUT)
    print(f"OK 已生成 {OUT}，共 {len(list(check.slides))} 页")


if __name__ == "__main__":
    main()
